  pdfChooseDestination: invoke("pdf:choose-destination"),
  pdfCancel: invoke("pdf:cancel"),
  onPdfProgress: on("pdf:progress"),
  copyImage: invoke("image:copy"),
  imageBytes: invoke("image:bytes"),
  bootstrap: invoke("app:bootstrap"),
  chooseWorkspace: invoke("workspace:choose"),
  openWorkspace: invoke("workspace:open"),
  tree: invoke("workspace:tree"),
  search: invoke("workspace:search"),
  cancelSearch: invoke("workspace:cancel-search"),
  read: invoke("file:read"),
  save: invoke("file:save"),
  saveCopy: invoke("file:save-copy"),
  create: invoke("file:create"),
  move: invoke("file:move"),
  moveSelection: invoke("file:move-selection"),
  trashSelection: invoke("file:trash-selection"),
